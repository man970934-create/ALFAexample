export function makeInsights(company: Company, role: Role): Insight[] {
  return events
    .filter((event) => personal[company.id][event.id])
    .map((event): Insight => {
      const [score, impact, why, effect, risk, opportunity, action] =
        personal[company.id][event.id];
      const source: Source = {
        id: `news-${event.id}`,
        title: `Учебная новость · ${event.topic}`,
        type: "news",
        date: event.date,
        excerpt: event.fact,
        synthetic: true,
      };
      const featureSources: Source[] = company.features.map((feature) => ({
        id: `${company.id}-${feature.id}`,
        title: `Профиль «${company.name}» · ${feature.id === "funding" ? "продукты" : feature.id === "sales" ? "бизнес-связи" : "отрасль"}`,
        type: "company",
        date: "2026-10-21",
        excerpt: feature.text,
        synthetic: true,
      }));
      const refs = [
        source.id,
        ...featureSources.map((s) => s.id),
        ...(event.bank ? [`bank-${event.id}`] : []),
      ];
      const claim = (
        id: string,
        text: string,
        origin: Claim["origin"] = "ai",
        sourceIds = refs,
      ): Claim => ({
        id: `${company.id}-${event.id}-${id}`,
        text,
        origin,
        sourceIds,
      });
      const adjusted =
        score +
        (role === "ceo" && event.id === "demand"
          ? 22
          : role === "treasurer" &&
              ["currency", "funding", "deposits"].includes(event.id)
            ? 12
            : 0);
      return {
        id: event.id,
        eventId: event.id,
        companyId: company.id,
        title: event.title,
        date: event.date,
        topic: event.topic,
        impact,
        score: adjusted,
        significance:
          adjusted >= 85 ? "high" : adjusted >= 60 ? "medium" : "low",
        fact: claim("fact", event.fact, "fact", [source.id]),
        why: claim("why", `${why} ${roleFocus[role]}`),
        effect: claim("effect", effect),
        risks: [claim("risk", risk)],
        opportunities: [claim("opportunity", opportunity)],
        actions: [claim("action", action)],
        bank: event.bank
          ? claim("bank", event.bank, "bank", [`bank-${event.id}`])
          : null,
        sources: [
          source,
          ...featureSources,
          ...(event.bank
            ? [
                {
                  id: `bank-${event.id}`,
                  title: `Демонстрационная аналитическая заметка · ${event.topic}`,
                  type: "bank" as const,
                  date: event.date,
                  excerpt: event.bank,
                  synthetic: true,
                },
              ]
            : []),
        ],
        limitations: [
          "Все события и выводы синтетические. Это не публикации и не рекомендации Альфа-Банка.",
          ...company.missing.map(
            (item) => `Нет данных: ${item.toLowerCase()}.`,
          ),
        ],
      };
    })
    .sort((a, b) => b.score - a.score);
}
